function validate(phone) {
    if (typeof phone !== 'string') {
        return false;
    }
    
    const cleaned = phone.replace(/\s+/g, '');
    
    const patterns = [
        /^\+1\d{10}$/,           // +11234567890
        /^\+1-\d{3}-\d{3}-\d{4}$/, // +1-123-456-7890
        /^\+1\.\d{3}\.\d{3}\.\d{4}$/, // +1.123.456.7890
        /^\+1\(\d{3}\)\d{3}-\d{4}$/, // +1(123)456-7890
        /^1\d{10}$/,             // 11234567890
        /^1-\d{3}-\d{3}-\d{4}$/, // 1-123-456-7890
        /^1\.\d{3}\.\d{3}\.\d{4}$/, // 1.123.456.7890
        /^1\(\d{3}\)\d{3}-\d{4}$/, // 1(123)456-7890
        /^\d{10}$/,              // 1234567890
        /^\d{3}-\d{3}-\d{4}$/,   // 123-456-7890
        /^\(\d{3}\)\d{3}-\d{4}$/, // (123)456-7890
        /^\(\d{3}\) \d{3}-\d{4}$/ // (123) 456-7890
    ];
    
    return patterns.some(pattern => pattern.test(cleaned));
}
